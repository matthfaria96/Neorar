#!/bin/sh
# Builds build/Neorar.app (release, universal when possible) and signs it ad hoc.
# Usage: ./build-app.sh [--install]   (--install copies the app to /Applications)
set -eu
cd "$(dirname "$0")"

# SwiftUI's macro plugins ship with Xcode, not with the Command Line Tools.
export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"

./scripts/fetch-7zip.sh

if swift build -c release --arch arm64 --arch x86_64 >/tmp/neorar-build.log 2>&1; then
  BIN="$(swift build -c release --arch arm64 --arch x86_64 --show-bin-path)/Neorar"
else
  echo "Build universal indisponível; gerando só para $(uname -m)."
  swift build -c release
  BIN="$(swift build -c release --show-bin-path)/Neorar"
fi

APP="build/Neorar.app"
CONTENTS="$APP/Contents"
rm -rf "$APP"
mkdir -p "$CONTENTS/MacOS" "$CONTENTS/Resources/Licenses"

cp "$BIN" "$CONTENTS/MacOS/Neorar"

# Finder Sync extension (right-click "Extrair Aqui" / "Extrair Para…").
APPEX="$CONTENTS/PlugIns/NeorarFinder.appex"
mkdir -p "$APPEX/Contents/MacOS"
SDK="$(xcrun --show-sdk-path)"
for ARCH in arm64 x86_64; do
  xcrun swiftc -target "$ARCH-apple-macos26.0" -sdk "$SDK" -O -parse-as-library -application-extension \
    -module-name NeorarFinder Extensions/FinderSync/FinderSync.swift -framework FinderSync \
    -Xlinker -e -Xlinker _NSExtensionMain -o "/tmp/neorar-finder-$ARCH"
done
lipo -create /tmp/neorar-finder-arm64 /tmp/neorar-finder-x86_64 -output "$APPEX/Contents/MacOS/NeorarFinder"
rm -f /tmp/neorar-finder-arm64 /tmp/neorar-finder-x86_64
cp Extensions/FinderSync/Info.plist "$APPEX/Contents/Info.plist"
mkdir -p "$APPEX/Contents/Resources"
cp -R Resources/Localizations/FinderSync/*.lproj "$APPEX/Contents/Resources/"
cp Vendor/7zz "$CONTENTS/MacOS/7zz"
cp Resources/Info.plist "$CONTENTS/Info.plist"
# Interface translations (generated by scripts/make-localizations.py).
for LPROJ in Resources/Localizations/*.lproj; do cp -R "$LPROJ" "$CONTENTS/Resources/"; done
printf 'APPL????' > "$CONTENTS/PkgInfo"

ICONSET="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$ICONSET"
for SIZE in 16 32 128 256 512; do
  sips -z $SIZE $SIZE Resources/icon_1024.png --out "$ICONSET/icon_${SIZE}x${SIZE}.png" >/dev/null
  DOUBLE=$((SIZE * 2))
  sips -z $DOUBLE $DOUBLE Resources/icon_1024.png --out "$ICONSET/icon_${SIZE}x${SIZE}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$CONTENTS/Resources/AppIcon.icns"

cp Sources/CUnrar/unrar/license.txt "$CONTENTS/Resources/Licenses/UnRAR-license.txt"
cp Vendor/7-Zip-License.txt "$CONTENTS/Resources/Licenses/7-Zip-License.txt"
cp THIRD_PARTY_NOTICES.md "$CONTENTS/Resources/Licenses/"

strip -x "$CONTENTS/MacOS/Neorar" 2>/dev/null || true
codesign --force --options runtime --sign - "$CONTENTS/MacOS/7zz"
codesign --force --options runtime --entitlements Extensions/FinderSync/FinderSync.entitlements --sign - "$APPEX"
codesign --force --options runtime --sign - "$APP"
codesign --verify --strict "$APP"

echo "Pronto: $APP ($(du -sh "$APP" | cut -f1))"

if [ "${1:-}" = "--install" ]; then
  rm -rf /Applications/Neorar.app
  cp -R "$APP" /Applications/
  /System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f /Applications/Neorar.app
  /System/Library/CoreServices/pbs -update 2>/dev/null || true
  echo "Instalado em /Applications/Neorar.app"
fi
