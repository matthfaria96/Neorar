#!/usr/bin/env python3 -I
"""Writes Resources/Localizations/<lang>.lproj/Localizable.strings from scripts/translations.py.

Usage: python3 scripts/make-localizations.py [keys.txt]
With a keys file (one key per line, from `swift build -Xswiftc -emit-localized-strings`), it also
reports keys that still lack a translation.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from translations import T, FINDER, LANGUAGES  # noqa: E402

ROOT = os.path.dirname(HERE)


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write(directory, table, index):
    os.makedirs(directory, exist_ok=True)
    lines = ["/* Generated by scripts/make-localizations.py — do not edit by hand. */", ""]
    for key in sorted(table):
        value = table[key] if index is None else table[key][index]
        lines.append(f'"{escape(key)}" = "{escape(value)}";')
    with open(os.path.join(directory, "Localizable.strings"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def main():
    out = os.path.join(ROOT, "Resources", "Localizations")
    for i, language in enumerate(LANGUAGES):
        write(os.path.join(out, f"{language}.lproj"), T, i)
        write(os.path.join(out, "FinderSync", f"{language}.lproj"), FINDER, i)
    # pt-BR is the development language: keys are already Portuguese.
    write(os.path.join(out, "pt-BR.lproj"), {k: k for k in T}, None)
    write(os.path.join(out, "FinderSync", "pt-BR.lproj"), {k: k for k in FINDER}, None)

    if len(sys.argv) > 1:
        keys = [k for k in open(sys.argv[1], encoding="utf-8").read().split("\n") if k.strip()]
        missing = [k for k in keys if k not in T]
        for key in missing:
            print("faltando:", repr(key))
        print(f"{len(keys) - len(missing)}/{len(keys)} chaves traduzidas")


if __name__ == "__main__":
    main()
